  'google-analytics': 'siGoogleanalytics', 'huggingface': 'siHuggingface',
  'machine-learning': null, 'deep-learning': null, 'llm': null, 'nlp': null,
  'quickbooks': 'siQuickbooks', 'linux': 'siLinux', 'git': 'siGit', 'docker': 'siDocker',
  'kubernetes': 'siKubernetes', 'terraform': 'siTerraform', 'spark': 'siApachespark',
  'airflow': 'siApacheairflow', 'dbt': null, 'pandas': 'siPandas', 'langchain': 'siLangchain',
  'grasshopper': null, 'dynamo': null, 'archicad': 'siArchicad', 'vectorworks': 'siVectorworks',
  'blender': 'siBlender', 'unity': 'siUnity', 'figma': 'siFigma', 'zbrush': null,
  'substance': null, 'touchdesigner': null, 'houdini': 'siHoudini', 'nuke': 'siNuke',
  'ableton': null, 'pro-tools': 'siProtools', 'wordpress': 'siWordpress',
  'semrush': 'siSemrush', 'sagemaker': null, 'microstation': 'siBentley', 'mastercam': null,
  'siemens-nx': 'siSiemens', 'etabs': null, 'tekla': 'siTrimble', 'bluebeam': null,
  'procore': null, 'toast-pos': null, 'epic-ehr': null, 'bloomberg': null,
